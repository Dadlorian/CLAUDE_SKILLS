-- ============================================
-- INFORMATION MART VIEWS
-- ============================================

-- Denormalized view for reporting: Customer Orders
CREATE OR REPLACE VIEW INFORMATION_MART.VW_CUSTOMER_ORDERS AS
SELECT
    hc.CUSTOMER_ID,
    sc.CUSTOMER_NAME,
    sc.EMAIL,
    sc.CUSTOMER_SEGMENT,
    ho.ORDER_ID,
    so.ORDER_NUMBER,
    so.ORDER_DATE,
    so.ORDER_STATUS,
    so.TOTAL_AMOUNT
FROM RAW_VAULT.HUB_CUSTOMER hc
JOIN RAW_VAULT.SAT_CUSTOMER sc
    ON hc.CUSTOMER_HK = sc.CUSTOMER_HK
    AND sc.LOAD_END_DATE IS NULL  -- Current record
JOIN RAW_VAULT.LINK_CUSTOMER_ORDER lco
    ON hc.CUSTOMER_HK = lco.CUSTOMER_HK
JOIN RAW_VAULT.HUB_ORDER ho
    ON lco.ORDER_HK = ho.ORDER_HK
JOIN RAW_VAULT.SAT_ORDER so
    ON ho.ORDER_HK = so.ORDER_HK
    AND so.LOAD_END_DATE IS NULL;

-- Historical analysis view: Customer changes over time
CREATE OR REPLACE VIEW INFORMATION_MART.VW_CUSTOMER_HISTORY AS
SELECT
    hc.CUSTOMER_ID,
    sc.CUSTOMER_NAME,
    sc.EMAIL,
    sc.CUSTOMER_SEGMENT,
    sc.CUSTOMER_TIER,
    sc.LOAD_DATE AS EFFECTIVE_FROM,
    COALESCE(sc.LOAD_END_DATE, '9999-12-31'::TIMESTAMP) AS EFFECTIVE_TO,
    CASE WHEN sc.LOAD_END_DATE IS NULL THEN TRUE ELSE FALSE END AS IS_CURRENT
FROM RAW_VAULT.HUB_CUSTOMER hc
JOIN RAW_VAULT.SAT_CUSTOMER sc
    ON hc.CUSTOMER_HK = sc.CUSTOMER_HK
ORDER BY hc.CUSTOMER_ID, sc.LOAD_DATE DESC;

