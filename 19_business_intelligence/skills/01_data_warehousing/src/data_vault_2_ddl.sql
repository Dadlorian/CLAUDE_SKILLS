-- Data Vault 2.0 DDL Implementation
-- Platform: Snowflake (adaptable to other platforms)
-- Description: Complete Data Vault 2.0 architecture with Hubs, Links, and Satellites

-- ============================================
-- DATABASE AND SCHEMA SETUP
-- ============================================

CREATE DATABASE IF NOT EXISTS DATA_VAULT;
USE DATABASE DATA_VAULT;

CREATE SCHEMA IF NOT EXISTS RAW_VAULT;
CREATE SCHEMA IF NOT EXISTS BUSINESS_VAULT;
CREATE SCHEMA IF NOT EXISTS INFORMATION_MART;

-- ============================================
-- HUB TABLES (Business Keys)
-- ============================================

-- Hub Customer: Unique customers
CREATE OR REPLACE TABLE RAW_VAULT.HUB_CUSTOMER (
    CUSTOMER_HK VARCHAR(32) PRIMARY KEY,  -- Hash key
    CUSTOMER_ID VARCHAR(50) NOT NULL,     -- Business key
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    -- Metadata
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Hub table for Customer business entities';

-- Hub Product: Unique products
CREATE OR REPLACE TABLE RAW_VAULT.HUB_PRODUCT (
    PRODUCT_HK VARCHAR(32) PRIMARY KEY,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Hub table for Product business entities';

-- Hub Order: Unique orders
CREATE OR REPLACE TABLE RAW_VAULT.HUB_ORDER (
    ORDER_HK VARCHAR(32) PRIMARY KEY,
    ORDER_ID VARCHAR(50) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Hub table for Order business entities';

-- Hub Store: Unique stores
CREATE OR REPLACE TABLE RAW_VAULT.HUB_STORE (
    STORE_HK VARCHAR(32) PRIMARY KEY,
    STORE_ID VARCHAR(50) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Hub table for Store business entities';

-- Hub Supplier: Unique suppliers
CREATE OR REPLACE TABLE RAW_VAULT.HUB_SUPPLIER (
    SUPPLIER_HK VARCHAR(32) PRIMARY KEY,
    SUPPLIER_ID VARCHAR(50) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Hub table for Supplier business entities';

-- ============================================
-- LINK TABLES (Relationships)
-- ============================================

-- Link Order Line: Relationship between Order and Product
CREATE OR REPLACE TABLE RAW_VAULT.LINK_ORDER_LINE (
    ORDER_LINE_HK VARCHAR(32) PRIMARY KEY,
    ORDER_HK VARCHAR(32) NOT NULL,
    PRODUCT_HK VARCHAR(32) NOT NULL,
    -- Optional: Additional business keys for grain
    LINE_NUMBER INTEGER,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    -- Foreign keys
    CONSTRAINT FK_ORDER_LINE_ORDER FOREIGN KEY (ORDER_HK)
        REFERENCES RAW_VAULT.HUB_ORDER(ORDER_HK),
    CONSTRAINT FK_ORDER_LINE_PRODUCT FOREIGN KEY (PRODUCT_HK)
        REFERENCES RAW_VAULT.HUB_PRODUCT(PRODUCT_HK)
)
COMMENT = 'Link table connecting Orders to Products';

-- Link Customer Order: Relationship between Customer and Order
CREATE OR REPLACE TABLE RAW_VAULT.LINK_CUSTOMER_ORDER (
    CUSTOMER_ORDER_HK VARCHAR(32) PRIMARY KEY,
    CUSTOMER_HK VARCHAR(32) NOT NULL,
    ORDER_HK VARCHAR(32) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_CUST_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_HK)
        REFERENCES RAW_VAULT.HUB_CUSTOMER(CUSTOMER_HK),
    CONSTRAINT FK_CUST_ORDER_ORDER FOREIGN KEY (ORDER_HK)
        REFERENCES RAW_VAULT.HUB_ORDER(ORDER_HK)
)
COMMENT = 'Link table connecting Customers to Orders';

-- Link Product Supplier: Many-to-Many relationship
CREATE OR REPLACE TABLE RAW_VAULT.LINK_PRODUCT_SUPPLIER (
    PRODUCT_SUPPLIER_HK VARCHAR(32) PRIMARY KEY,
    PRODUCT_HK VARCHAR(32) NOT NULL,
    SUPPLIER_HK VARCHAR(32) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_PROD_SUPP_PRODUCT FOREIGN KEY (PRODUCT_HK)
        REFERENCES RAW_VAULT.HUB_PRODUCT(PRODUCT_HK),
    CONSTRAINT FK_PROD_SUPP_SUPPLIER FOREIGN KEY (SUPPLIER_HK)
        REFERENCES RAW_VAULT.HUB_SUPPLIER(SUPPLIER_HK)
)
COMMENT = 'Link table for Product-Supplier relationships';

-- Link Order Store: Order fulfillment location
CREATE OR REPLACE TABLE RAW_VAULT.LINK_ORDER_STORE (
    ORDER_STORE_HK VARCHAR(32) PRIMARY KEY,
    ORDER_HK VARCHAR(32) NOT NULL,
    STORE_HK VARCHAR(32) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_ORDER_STORE_ORDER FOREIGN KEY (ORDER_HK)
        REFERENCES RAW_VAULT.HUB_ORDER(ORDER_HK),
    CONSTRAINT FK_ORDER_STORE_STORE FOREIGN KEY (STORE_HK)
        REFERENCES RAW_VAULT.HUB_STORE(STORE_HK)
)
COMMENT = 'Link table connecting Orders to Stores';

-- ============================================
-- SATELLITE TABLES (Descriptive Attributes)
-- ============================================

-- Satellite Customer: Customer descriptive data
CREATE OR REPLACE TABLE RAW_VAULT.SAT_CUSTOMER (
    CUSTOMER_HK VARCHAR(32) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    LOAD_END_DATE TIMESTAMP_NTZ,
    -- Hash diff for change detection
    HASH_DIFF VARCHAR(32) NOT NULL,
    -- Descriptive attributes
    CUSTOMER_NAME VARCHAR(200),
    EMAIL VARCHAR(200),
    PHONE VARCHAR(50),
    CUSTOMER_SEGMENT VARCHAR(50),
    CUSTOMER_TIER VARCHAR(20),
    COUNTRY VARCHAR(100),
    STATE VARCHAR(100),
    CITY VARCHAR(100),
    POSTAL_CODE VARCHAR(20),
    -- Metadata
    RECORD_SOURCE VARCHAR(50) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    -- Primary key
    PRIMARY KEY (CUSTOMER_HK, LOAD_DATE),
    -- Foreign key
    CONSTRAINT FK_SAT_CUSTOMER_HUB FOREIGN KEY (CUSTOMER_HK)
        REFERENCES RAW_VAULT.HUB_CUSTOMER(CUSTOMER_HK)
)
COMMENT = 'Satellite with Customer descriptive attributes';

-- Satellite Product: Product descriptive data
CREATE OR REPLACE TABLE RAW_VAULT.SAT_PRODUCT (
    PRODUCT_HK VARCHAR(32) NOT NULL,
    LOAD_DATE TIMESTAMP_NTZ NOT NULL,
    LOAD_END_DATE TIMESTAMP_NTZ,
    HASH_DIFF VARCHAR(32) NOT NULL,
    -- Descriptive attributes
    PRODUCT_NAME VARCHAR(200),
    PRODUCT_DESCRIPTION VARCHAR(1000),
    SKU VARCHAR(100),
    BRAND VARCHAR(100),
    CATEGORY VARCHAR(100),
    SUBCATEGORY VARCHAR(100),
